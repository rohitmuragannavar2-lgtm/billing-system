CREATE TABLE users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 phone VARCHAR(30),
 password VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE menu_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(140) NOT NULL,
 description VARCHAR(500),
 category VARCHAR(40) NOT NULL,
 price DECIMAL(10,2) NOT NULL,
 vegetarian BOOLEAN NOT NULL DEFAULT TRUE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE customer_orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'PLACED',
 total_amount DECIMAL(10,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL,
 menu_item_id BIGINT NOT NULL,
 item_name VARCHAR(140) NOT NULL,
 quantity INT NOT NULL,
 unit_price DECIMAL(10,2) NOT NULL,
 line_total DECIMAL(10,2) NOT NULL,
 CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES customer_orders(id),
 CONSTRAINT fk_order_item_menu FOREIGN KEY (menu_item_id) REFERENCES menu_items(id)
);
CREATE TABLE bills (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL UNIQUE,
 bill_number VARCHAR(40) NOT NULL UNIQUE,
 subtotal DECIMAL(10,2) NOT NULL,
 tax DECIMAL(10,2) NOT NULL,
 grand_total DECIMAL(10,2) NOT NULL,
 generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 emailed_at TIMESTAMP NULL,
 CONSTRAINT fk_bill_order FOREIGN KEY (order_id) REFERENCES customer_orders(id)
);
CREATE TABLE bill_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 bill_id BIGINT NOT NULL,
 item_name VARCHAR(140) NOT NULL,
 quantity INT NOT NULL,
 unit_price DECIMAL(10,2) NOT NULL,
 line_total DECIMAL(10,2) NOT NULL,
 CONSTRAINT fk_bill_item_bill FOREIGN KEY (bill_id) REFERENCES bills(id)
);
